    expires_at   BIGINT,
    CONSTRAINT fk_forum_invitations_inviter_id__id
        FOREIGN KEY (inviter_id) REFERENCES users (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_forum_invitations_invitee_id__id
        FOREIGN KEY (invitee_id) REFERENCES users (id)
        ON DELETE CASCADE
);
CREATE UNIQUE INDEX forum_invitations_invite_code_unique ON forum_invitations (invite_code);

-- friend_requests
CREATE TABLE friend_requests (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_user  INTEGER     NOT NULL,
    to_user    INTEGER     NOT NULL,
    status     VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    message    VARCHAR(200),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_friend_requests_from_user__id
        FOREIGN KEY (from_user) REFERENCES users (id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_friend_requests_to_user__id
        FOREIGN KEY (to_user) REFERENCES users (id)
        ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX friend_requests_from_user_idx ON friend_requests (from_user);
CREATE INDEX friend_requests_to_user_idx   ON friend_requests (to_user);

-- friends  (composite PK: user_a, user_b)
CREATE TABLE friends (
    user_a       INTEGER      NOT NULL,
    user_b       INTEGER      NOT NULL,
    chat         INTEGER      NOT NULL,
    remark_for_a VARCHAR(100),
    remark_for_b VARCHAR(100),
    CONSTRAINT pk_friends PRIMARY KEY (user_a, user_b),
    CONSTRAINT fk_friends_user_a__id
        FOREIGN KEY (user_a) REFERENCES users (id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_friends_user_b__id
        FOREIGN KEY (user_b) REFERENCES users (id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_friends_chat__id
        FOREIGN KEY (chat) REFERENCES chats (id)
        ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX friends_user_a_idx ON friends (user_a);
CREATE INDEX friends_user_b_idx ON friends (user_b);
CREATE INDEX friends_chat_idx   ON friends (chat);

-- group_invitations
CREATE TABLE group_invitations (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat          INTEGER     NOT NULL,
    inviter       INTEGER     NOT NULL,
    target_user   INTEGER     NOT NULL,
    encrypted_key TEXT        NOT NULL,
    status        VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at    TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT fk_group_invitations_chat__id
        FOREIGN KEY (chat) REFERENCES chats (id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_group_invitations_inviter__id
        FOREIGN KEY (inviter) REFERENCES users (id)
        ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT fk_group_invitations_target_user__id
        FOREIGN KEY (target_user) REFERENCES users (id)
        ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE INDEX group_invitations_chat_idx ON group_invitations (chat);
